def test_pool_ci_meta_export_does_not_inherit_database_or_redis(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
) -> None:
    monkeypatch.setenv("DATABASE_URL", DISPOSABLE)
    monkeypatch.setenv("REDIS_URL", "redis://127.0.0.1:9/0")

    def refuse_database(*args: object, **kwargs: object) -> Never:
        raise AssertionError("Static export attempted database access")

    monkeypatch.setattr(migration_check, "engine_for", refuse_database)
    target = tmp_path / "meta.json"
    monkeypatch.setattr("sys.argv", [str(SCRIPT), str(target)])
    if dump_meta_main() != 0:
        pytest.fail("Static meta export failed")
    payload = json.loads(target.read_text(encoding="utf-8"))
    if not payload["enums"]["notification_ref_type"] or not payload["error_codes"]:
        pytest.fail("Static export omitted its real route data")


def test_pool_ci_application_still_rejects_uninitialized_database(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    connection = SimpleNamespace(execute=lambda *args: SimpleNamespace(scalar_one=lambda: None))
    engine = SimpleNamespace(connect=lambda: nullcontext(connection), dispose=lambda: None)
    monkeypatch.setattr(migration_check, "engine_for", lambda *args: engine)
    settings = Settings(app_env="test", database_url=DISPOSABLE, redis_url=None, _env_file=None)
    with (
        pytest.raises(migration_check.MigrationLineageError, match="DATABASE_SCHEMA_UNINITIALIZED"),
        TestClient(create_app(settings)),
    ):
        pass


@pytest.mark.parametrize(
    ("limit", "authorized", "stopped", "limited_response", "expected_calls"),
    [
        (0, True, False, False, 0),
        (2, True, False, False, 2),
        ("unlimited", True, False, False, 3),
        ("unlimited", False, False, False, 0),
        ("unlimited", True, True, False, 0),
        ("unlimited", True, False, True, 1),
    ],
)
def test_pool_ci_budget_and_authorization_still_fence_transport(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    limit: int | str,
    authorized: bool,
    stopped: bool,
    limited_response: bool,
    expected_calls: int,
) -> None:
    calls: list[str] = []
    monkeypatch.setattr(daily_bars, "DAILY_BARS_HTTP_LIMIT", limit)
    monkeypatch.setattr(daily_bars, "_record_run", lambda *args, **kwargs: None)
    monkeypatch.setattr(daily_bars, "covered", lambda *args: True)
    monkeypatch.setattr(
        daily_bars, "daily_universe", lambda *args: ["600000.SH", "000001.SZ", "600001.SH"]
    )
    stop = tmp_path / "STOP"
    if stopped:
        stop.touch()

    def upstream(code: str, start: dt.date, end: dt.date) -> tuple[int, object]:
        calls.append(code)
        return (429 if limited_response else 400), {}

    daily_bars.fetch_mairui_daily_bars(
        cast(Connection, object()),
        trade_date=dt.date(2026, 11, 10),
        user_id=uuid.UUID(int=1),
        transport=upstream,
        stop_path=stop,
        halt_path=tmp_path / "HALTED",
        grant_reader=lambda: object() if authorized else None,
        clock=lambda: dt.datetime(2026, 11, 10, 12, tzinfo=dt.UTC),
    )
    if len(calls) != expected_calls:
        pytest.fail(f"Transport fence changed: expected {expected_calls}, observed {len(calls)}")


def disposable_config(monkeypatch: pytest.MonkeyPatch) -> Config:
    if os.environ.get("CI57_DISPOSABLE_DATABASE_URL") != DISPOSABLE:
        pytest.skip("Requires the explicitly provisioned CI57 disposable database")
    monkeypatch.setenv("DATABASE_URL", DISPOSABLE)
    return Config(str(BACKEND / "alembic.ini"))


def test_pool_ci_active_metadata_has_no_upgrade_drift(monkeypatch: pytest.MonkeyPatch) -> None:
    command.check(disposable_config(monkeypatch))


def test_pool_ci_check_detects_paused_nullable_metadata_negative(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    config = disposable_config(monkeypatch)
    column = master_vendor_batches.c.source_licence_id
    original = column.nullable
    try:
        column.nullable = True
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
    finally:
        column.nullable = original


def test_pool_ci_database_rejects_paused_null_licence_scope(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    disposable_config(monkeypatch)
    engine = create_engine(DISPOSABLE)
    try:
        with engine.connect() as connection:
            transaction = connection.begin()
            try:
                with pytest.raises(IntegrityError) as error:
                    connection.execute(
                        text("""
                        INSERT INTO market.master_vendor_batches
                        (master_run_id,source_licence_id,status,attempt,requested_at,deadline_at)
                        VALUES (0,NULL,'skipped',1,now(),now())
                    """)
                    )
                if error.value.orig.sqlstate != "23502":
                    pytest.fail("Expected NOT NULL rejection, not a different database failure")
            finally:
                transaction.rollback()
    finally:
        engine.dispose()
