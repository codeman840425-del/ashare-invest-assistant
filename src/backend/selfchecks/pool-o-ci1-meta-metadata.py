@pytest.mark.parametrize(
    ("limit", "authorized", "stopped", "status", "raises", "expected_calls"),
    [
        (0, True, False, 400, "", 0),
        (2, True, False, 400, "", 2),
        (5, True, False, 400, "", 3),
        (5, False, False, 400, "", 0),
        (5, True, True, 400, "", 0),
        (5, True, False, 103, "", 1),
        (5, True, False, 429, "", 1),
        (5, True, False, 400, "daily_halt", 1),
        (5, True, False, 400, "egress_denied", 1),
    ],
)
def test_budget_loop_cap_stop_and_limits_with_fake_upstream(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    limit: int | str,
    authorized: bool,
    stopped: bool,
    status: int,
    raises: str,
    expected_calls: int,
) -> None:
    calls: list[str] = []
    runs: list[dict[str, object]] = []
    stop, halt = tmp_path / "STOP", tmp_path / "HALTED"
    if stopped:
        stop.touch()
    monkeypatch.setattr(daily_bars, "DAILY_BARS_BATCH_LIMIT", limit)
    monkeypatch.setattr(daily_bars, "covered", lambda *_args: True)
    monkeypatch.setattr(
        daily_bars, "daily_universe", lambda *_args: ["600000.SH", "000001.SZ", "600001.SH"]
    )

    def record(_conn: Connection, *_args: object, **kwargs: object) -> None:
        runs.append(kwargs)

    def upstream(code: str, _start: dt.date, _end: dt.date) -> tuple[int, None]:
        calls.append(code)
        if raises == "daily_halt":
            raise DailyHaltError("synthetic halt")
        if raises == "egress_denied":
            raise EgressDenied("core_denied")
        return status, None

    monkeypatch.setattr(daily_bars, "_record_run", record)
    owner = uuid.uuid4()
    written = daily_bars.fetch_mairui_daily_bars(
        Mock(spec=Connection),
        trade_date=dt.date(2026, 11, 11),
        user_id=owner,
        transport=upstream,
        stop_path=stop,
        halt_path=halt,
        grant_reader=lambda: (
            daily_bars.DailyBarsGrant(
                owner,
                uuid.UUID(int=2),
                uuid.UUID(int=3),
                dt.datetime(2026, 11, 10, tzinfo=dt.UTC),
                dt.datetime(2026, 11, 12, tzinfo=dt.UTC),
                "0" * 64,
            )
            if authorized
            else None
        ),
        clock=lambda: dt.datetime(2026, 11, 11, tzinfo=dt.UTC),
    )
    require(written == 0 and len(calls) == expected_calls, "budget/stop/limit call count changed")
    require(len(runs) == 1, "run recording changed")
    if status in (103, 429) or raises:
        require(halt.is_file(), "upstream halt not persisted")
    if limit == 2:
        stats = runs[0]["stats"]
        require(
            isinstance(stats, dict) and stats["issues"].count("daily_bars_quota_deferred") == 1,
            "cap no longer defers remaining code",
        )
