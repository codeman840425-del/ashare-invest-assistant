def test_ascii_ini_preserves_all_configuration_and_single_active_head() -> None:
    source = os.environ.get("OCI1_BASE_INI_FILE")
    if not source:
        pytest.fail("explicit original INI fixture required")
    baseline = Path(source).read_bytes()
    baseline_blob = hashlib.sha1(
        b"blob " + str(len(baseline)).encode() + b"\0" + baseline, usedforsecurity=False
    ).hexdigest()
    require(
        baseline_blob == "ac839cd967e5781e79b3c519ab9393e7a460274d", "wrong original INI fixture"
    )
    current = (BACKEND / "alembic.ini").read_bytes()
    with pytest.raises(UnicodeDecodeError):
        baseline.decode("cp936")
    original_config, current_config = configparser.ConfigParser(), configparser.ConfigParser()
    original_config.read_string(baseline.decode("utf-8"))
    for encoding in ("ascii", "utf-8", "cp936", "cp1252"):
        current_config.read_string(current.decode(encoding))
        require(original_config.sections() == current_config.sections(), "INI sections changed")
        for section in original_config.sections():
            require(
                dict(original_config.items(section, raw=True))
                == dict(current_config.items(section, raw=True)),
                "INI values changed",
            )
    script = ScriptDirectory.from_config(Config(str(BACKEND / "alembic.ini")))
    require(script.get_heads() == ["0034"], "active migration head changed")
    require(
        "0021" not in {item.revision for item in script.walk_revisions()}, "paused 0021 activated"
    )


