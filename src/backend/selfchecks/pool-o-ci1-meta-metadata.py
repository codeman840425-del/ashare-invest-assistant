def test_physical_schema_drift_is_detected_and_removed(monkeypatch: pytest.MonkeyPatch) -> None:
    config = configured(monkeypatch)
    engine = create_engine(disposable_url("migrations"))
    try:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE app.signal_states ADD COLUMN o_ci1_drift_marker text"))
        try:
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
        finally:
            with engine.begin() as conn:
                conn.execute(text("ALTER TABLE app.signal_states DROP COLUMN o_ci1_drift_marker"))
        command.check(config)
    finally:
        engine.dispose()


