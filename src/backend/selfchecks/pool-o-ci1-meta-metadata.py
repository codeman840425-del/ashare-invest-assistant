def require(condition: bool, message: str) -> None:
    if not condition:
        pytest.fail(message)


def disposable_url(kind: str) -> str:
    raw = os.environ.get(f"OCI1_{kind.upper()}_URL")
    if not raw:
        pytest.fail("Explicit O-CI1 disposable URL required; no default database")
    parsed = make_url(raw)
    require(parsed.host == "127.0.0.1" and parsed.port == 55481, "wrong synthetic PG endpoint")
    require(parsed.database == f"oci1_20261111_{kind}", "wrong synthetic database")
    return raw


def configured(monkeypatch: pytest.MonkeyPatch) -> Config:
    monkeypatch.setenv("DATABASE_URL", disposable_url("migrations"))
    return Config(str(BACKEND / "alembic.ini"))


def test_export_never_inherits_database_or_redis(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setenv("DATABASE_URL", disposable_url("meta_empty"))
    monkeypatch.setenv("REDIS_URL", "redis://127.0.0.1:9/0")
    monkeypatch.setenv("APP_ENV", "prod")

    def denied(*_args: object, **_kwargs: object) -> Never:
        raise AssertionError("offline export attempted a storage connection")

    monkeypatch.setattr(migration_check, "engine_for", denied)
    monkeypatch.setattr(redis.Redis, "from_url", denied)
    monkeypatch.syspath_prepend(str(BACKEND.parents[1]))
    from scripts.ci import dump_meta_enums as module

    require(Path(module.__file__).resolve() == SCRIPT.resolve(), "wrong export module origin")
    output = tmp_path / "meta.json"
    monkeypatch.setattr("sys.argv", [str(SCRIPT), str(output)])
    require(module.main() == 0, "offline export failed")
    payload = json.loads(output.read_text(encoding="utf-8"))
    require(bool(payload["enums"]["notification_ref_type"]), "real enums omitted")
    require(bool(payload["error_codes"]), "real error-code projection omitted")


